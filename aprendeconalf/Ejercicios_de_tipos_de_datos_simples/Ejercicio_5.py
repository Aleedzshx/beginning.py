horas_trabajadas = int(input("Ingrese las horas trabajadas: ")) #Se define la variable horas_trabajadas con el valor ingresado por el usuario

tarifa_hora = int(input("Ingrese la tarifa por hora: ")) #Se define la variable tarifa_hora con el valor ingresado por el usuario

sueldo_bruto = horas_trabajadas * tarifa_hora #Se define la variable sueldo_bruto con el valor de las horas trabajadas por la tarifa por hora


print("El sueldo bruto es: ", sueldo_bruto , "pesos") #Se imprime el valor de la variable sueldo_bruto