n = int(input("Ingrese un numero entero: ")) #Se define la variable n con el valor ingresado por el usuario

suma = n * (n + 1) / 2 #Se define la variable suma con el valor de la suma de los numeros enteros desde 1 hasta n

print("La suma de los numeros enteros desde 1 hasta", n, "es:", suma) #Se imprime el valor de la variable suma
